#!/usr/bin/env python3
"""coderabbit.py: render, check and migrate the fleet's .coderabbit.yaml.

CodeRabbit reads ONE file per repository, `.coderabbit.yaml` (or the older
`.coderabbit.yml`) at its root. The fleet needs two owners for that one file:
this repository imposes a central part (stub/coderabbit/), and each repository
keeps its own settings. YAML has no way to hold two `reviews:` keys, so the
repository's part lives in `.coderabbit.local.yaml`, which CodeRabbit never
reads, and `.coderabbit.yaml` is rendered from both:

    managed  = central.yaml, then owners/<owner>.yaml on top
    local    = .coderabbit.local.yaml, or defaults.yaml when there is none
    rendered = local with managed laid on top (see overlay)

enforce.sh calls `plan`; the other commands exist for people and tests.

    coderabbit.py plan     --root DIR --owner OWNER --current DIR --out DIR
    coderabbit.py render   --root DIR --owner OWNER [--local FILE]
    coderabbit.py validate --root DIR FILE...
    coderabbit.py diff     BEFORE AFTER

`plan` reads whichever of the three files the default branch carries from
--current and writes into --out:

    kind      present | create | migrate | sync
    write/    the files to write, under their own names (none when present)
    delete    one name per line: files to remove (.coderabbit.yml)
    body.md   the pull request body, with the semantic diff
    note      one line for the report

and exits 0. It exits 3 when the repository's own content must be fixed by a
person (a local file that does not parse, a rendering the schema refuses, a
migration that would change more than the managed keys) and prints why, and 2
on a usage error. It writes nothing then, so enforce.sh writes nothing either.

Only the standard library and PyYAML: the enforce job holds a write token on
every repository of every owner, and a package installed into it would run
with those tokens. The JSON Schema subset the pinned schema uses is checked
here (Validator), and tests/run.sh holds it to the `jsonschema` package on
every file it checks.
"""
import copy
import json
import os
import re
import subprocess
import sys

import yaml

LOCAL = ".coderabbit.local.yaml"
YAML = ".coderabbit.yaml"
YML = ".coderabbit.yml"
GENERATED = "# GENERATED by kodflow/post-commit enforce. Do not edit this file:"
SCHEMA_URL = "https://coderabbit.ai/integrations/schema.v2.json"
README = "https://github.com/kodflow/post-commit#coderabbit"

# The comment the 08/11/2026 campaign wrote next to the exclusion lists in the
# hand-written files. It describes a copy those files no longer hold once the
# lists are central, so a migration drops it with them.
LEGACY_COMMENT = (
    "# Sync PRs opened by kodflow-ci[bot] (post-commit enforce, runner-template) are",
    "# excluded from review to save the CodeRabbit quota; the same lists live in",
    "# kodflow/making.codes coderabbit/override-*.yaml.",
)


class Refused(Exception):
    """The repository's content cannot be rendered: a person has to fix it."""


# --- YAML --------------------------------------------------------------------
# CodeRabbit reads YAML 1.2, where `off`, `yes` and `2026-11-09` are strings;
# PyYAML's SafeLoader reads YAML 1.1, where they are a boolean, a boolean and a
# date. Read with 1.1 rules, settings.yaml's `mode: off` would come back out as
# `mode: false`, which the schema refuses. So files are read with the 1.2 core
# schema, and written so that both readings agree (see Dumper).

class Loader(yaml.SafeLoader):
    """YAML 1.2 core schema, and a duplicate key is an error, not a last-wins."""


Loader.yaml_implicit_resolvers = {}
_IMPLICIT = [
    ("tag:yaml.org,2002:null", r"^(?:~|null|Null|NULL|)$", list("~nN") + [""]),
    ("tag:yaml.org,2002:bool", r"^(?:true|True|TRUE|false|False|FALSE)$", list("tTfF")),
    ("tag:yaml.org,2002:int", r"^(?:[-+]?[0-9]+|0o[0-7]+|0x[0-9a-fA-F]+)$", list("-+0123456789")),
    ("tag:yaml.org,2002:float",
     r"^(?:[-+]?(?:\.[0-9]+|[0-9]+(?:\.[0-9]*)?)(?:[eE][-+]?[0-9]+)?"
     r"|[-+]?\.(?:inf|Inf|INF)|\.(?:nan|NaN|NAN))$", list("-+.0123456789")),
    ("tag:yaml.org,2002:merge", r"^<<$", ["<"]),
]
for _tag, _rx, _first in _IMPLICIT:
    Loader.add_implicit_resolver(_tag, re.compile(_rx), _first)


def _int12(loader, node):
    v = loader.construct_scalar(node)
    sign = -1 if v.startswith("-") else 1
    v = v.lstrip("+-")
    if v.startswith("0o"):
        return sign * int(v[2:], 8)
    if v.startswith("0x"):
        return sign * int(v[2:], 16)
    return sign * int(v, 10)


def _float12(loader, node):
    v = loader.construct_scalar(node).lower()
    if v.endswith(".inf"):
        return float("-inf") if v.startswith("-") else float("inf")
    if v == ".nan":
        return float("nan")
    return float(v)


def _mapping(loader, node, deep=False):
    loader.flatten_mapping(node)
    seen = {}
    for key_node, _ in node.value:
        key = loader.construct_object(key_node, deep=True)
        if key in seen:
            raise Refused(f"duplicate key {key!r} at line {key_node.start_mark.line + 1}"
                          f" (first at line {seen[key] + 1})")
        seen[key] = key_node.start_mark.line
    return yaml.SafeLoader.construct_mapping(loader, node, deep=True)


def _map_ctor(loader, node):
    return _mapping(loader, node)


Loader.add_constructor("tag:yaml.org,2002:int", _int12)
Loader.add_constructor("tag:yaml.org,2002:float", _float12)
Loader.add_constructor("tag:yaml.org,2002:map", _map_ctor)


def _resolves_12(value):
    """The tag YAML 1.2 gives `value` written plain, or None for a string."""
    for tag, rx, _ in _IMPLICIT:
        if tag != "tag:yaml.org,2002:merge" and re.match(rx, value):
            return tag
    return None


class Dumper(yaml.SafeDumper):
    """Writes what Loader and yaml.SafeLoader both read back unchanged."""

    def ignore_aliases(self, data):
        return True

    def increase_indent(self, flow=False, indentless=False):
        # List items indented under their key, as the fleet's files write them.
        return super().increase_indent(flow, False)


def _str(dumper, value):
    # A multi-line string goes out as a literal block, as people write them.
    # PyYAML falls back to a quoted style on its own when a block cannot hold
    # the value (trailing spaces, tabs). A string YAML 1.2 would read as
    # something else is quoted; SafeDumper already quotes what 1.1 would.
    style = "|" if "\n" in value else ("'" if _resolves_12(value) else None)
    return dumper.represent_scalar("tag:yaml.org,2002:str", value, style=style)


Dumper.add_representer(str, _str)


def load_text(text, what):
    try:
        data = yaml.load(text, Loader=Loader)
    except Refused as e:
        raise Refused(f"{what}: {e}") from None
    except yaml.YAMLError as e:
        raise Refused(f"{what} is not valid YAML: {str(e).splitlines()[0]}") from None
    if data is None:
        return {}
    if not isinstance(data, dict):
        raise Refused(f"{what} is not a mapping at its top level")
    return data


def load_file(path, what=None):
    with open(path, encoding="utf-8") as fh:
        return load_text(fh.read(), what or os.path.basename(path))


def dump(data):
    text = yaml.dump(data, Dumper=Dumper, sort_keys=False, allow_unicode=True,
                     default_flow_style=False, width=100, indent=2)
    # Fail closed: a rendering that a 1.1 or a 1.2 reader would read back as
    # anything else is never written.
    for loader in (Loader, yaml.SafeLoader):
        if yaml.load(text, Loader=loader) != data:
            raise Refused(f"the rendering does not read back unchanged under {loader.__name__}")
    return text


# --- merge -------------------------------------------------------------------

def overlay(base, managed):
    """`base` with `managed` laid on top. Mappings merge key by key, the base's
    order kept and managed keys it lacks appended. A list in `managed` comes
    first and in full, followed by the base's items it does not already hold.
    Anything else in `managed` replaces the base's value, whatever its type."""
    if isinstance(managed, dict):
        out = copy.deepcopy(base) if isinstance(base, dict) else {}
        for k, v in managed.items():
            out[k] = overlay(out.get(k), v)
        return out
    if isinstance(managed, list):
        rest = [x for x in base if x not in managed] if isinstance(base, list) else []
        return copy.deepcopy(managed) + copy.deepcopy(rest)
    return copy.deepcopy(managed)


def leaves(data, path=()):
    """Every leaf path of a managed mapping: a list or a scalar is a leaf."""
    if isinstance(data, dict) and data:
        for k, v in data.items():
            yield from leaves(v, path + (k,))
    else:
        yield path


class Central:
    def __init__(self, root, owner):
        self.root = root
        self.owner = owner
        files = [os.path.join(root, "central.yaml")]
        extra = os.path.join(root, "owners", f"{owner}.yaml")
        if os.path.exists(extra):
            files.append(extra)
        self.managed = {}
        for f in files:
            self.managed = overlay(self.managed, load_file(f, os.path.relpath(f, root)))
        self.defaults = load_file(os.path.join(root, "defaults.yaml"), "defaults.yaml")
        self.sources = [os.path.relpath(f, root) for f in files]
        self.validator = Validator(os.path.join(root, "schema.v2.json"))
        self.managed_leaves = set(leaves(self.managed))

    def ref(self, name):
        """`name@<blob>` of a central file: its content, not this repository's
        HEAD, so that a commit here that does not touch the template changes
        no rendering and opens no pull request anywhere."""
        path = os.path.join(self.root, name)
        try:
            blob = subprocess.run(["git", "hash-object", path], capture_output=True,
                                  text=True, check=True).stdout.strip()[:12]
        except (OSError, subprocess.CalledProcessError):
            raise Refused(f"cannot hash {name}") from None
        return f"{name}@{blob}"

    def render(self, local_text):
        """(rendered text, its data). local_text None: the defaults."""
        if local_text is None:
            base, src = copy.deepcopy(self.defaults), self.ref("defaults.yaml") + " (no " + LOCAL + ")"
        else:
            base, src = load_text(local_text, LOCAL), LOCAL
        data = overlay(base, self.managed)
        problems = self.validator.errors(data)
        if problems:
            raise Refused("the rendered " + YAML + " fails the schema: " + "; ".join(problems[:5]))
        header = [
            f"# yaml-language-server: $schema={SCHEMA_URL}",
            GENERATED,
            f"# edit {LOCAL}, and enforce renders this file again from it.",
            "# Central part, imposed: kodflow/post-commit "
            + " + ".join(self.ref(s) for s in self.sources) + ",",
            f"# laid over the repository's own part: {src}.",
            f"# How and why: {README}",
            "",
        ]
        return "\n".join(header) + dump(data), data


# --- JSON Schema, the subset the pinned schema uses ----------------------------

class Validator:
    """The draft 2020-12 keywords schema.v2.json uses, and no other: a schema
    that starts using one this does not know is refused outright, rather than
    half-checked."""
    CHECKS = {"type", "enum", "const", "properties", "additionalProperties", "required",
              "items", "minItems", "maxItems", "minLength", "maxLength", "minimum",
              "maximum", "pattern", "propertyNames", "anyOf"}
    NOTES = {"$schema", "description", "default", "deprecated", "enumNames", "title",
             "examples", "markdownDescription", "x-undocumented"}

    def __init__(self, path):
        with open(path, encoding="utf-8") as fh:
            self.schema = json.load(fh)
        self._audit(self.schema, "#")

    def _audit(self, s, where):
        if not isinstance(s, dict):
            if isinstance(s, bool):
                return
            raise Refused(f"schema: not a schema at {where}")
        unknown = set(s) - self.CHECKS - self.NOTES
        if unknown:
            raise Refused(f"schema: unsupported keyword(s) {sorted(unknown)} at {where}")
        for k, v in s.get("properties", {}).items():
            self._audit(v, f"{where}/properties/{k}")
        for k in ("items", "propertyNames"):
            if k in s:
                self._audit(s[k], f"{where}/{k}")
        if isinstance(s.get("additionalProperties"), dict):
            self._audit(s["additionalProperties"], f"{where}/additionalProperties")
        for i, sub in enumerate(s.get("anyOf", [])):
            self._audit(sub, f"{where}/anyOf/{i}")

    @staticmethod
    def _is(value, t):
        return {
            "object": lambda v: isinstance(v, dict),
            "array": lambda v: isinstance(v, list),
            "string": lambda v: isinstance(v, str),
            "boolean": lambda v: isinstance(v, bool),
            "null": lambda v: v is None,
            "integer": lambda v: (isinstance(v, int) and not isinstance(v, bool))
            or (isinstance(v, float) and v.is_integer()),
            "number": lambda v: isinstance(v, (int, float)) and not isinstance(v, bool),
        }[t](value)

    @staticmethod
    def _same(a, b):
        # JSON equality: true is not 1.
        if isinstance(a, bool) or isinstance(b, bool):
            return isinstance(a, bool) and isinstance(b, bool) and a == b
        return a == b

    def errors(self, data):
        out = []
        self._check(self.schema, data, "", out)
        return out

    def _check(self, s, v, at, out):
        where = at or "(root)"
        if s is True:
            return
        if s is False:
            out.append(f"{where}: not allowed")
            return
        if "type" in s:
            types = s["type"] if isinstance(s["type"], list) else [s["type"]]
            if not any(self._is(v, t) for t in types):
                out.append(f"{where}: expected {'/'.join(types)}, got {type(v).__name__}")
                return
        if "enum" in s and not any(self._same(v, e) for e in s["enum"]):
            out.append(f"{where}: {v!r} is not one of {s['enum']}")
        if "const" in s and not self._same(v, s["const"]):
            out.append(f"{where}: must be {s['const']!r}")
        if isinstance(v, str):
            if "minLength" in s and len(v) < s["minLength"]:
                out.append(f"{where}: shorter than {s['minLength']}")
            if "maxLength" in s and len(v) > s["maxLength"]:
                out.append(f"{where}: longer than {s['maxLength']} characters ({len(v)})")
            if "pattern" in s and not re.search(s["pattern"], v, re.ASCII):
                out.append(f"{where}: does not match {s['pattern']}")
        if isinstance(v, (int, float)) and not isinstance(v, bool):
            if "minimum" in s and v < s["minimum"]:
                out.append(f"{where}: below {s['minimum']}")
            if "maximum" in s and v > s["maximum"]:
                out.append(f"{where}: above {s['maximum']}")
        if isinstance(v, list):
            if "minItems" in s and len(v) < s["minItems"]:
                out.append(f"{where}: fewer than {s['minItems']} items")
            if "maxItems" in s and len(v) > s["maxItems"]:
                out.append(f"{where}: more than {s['maxItems']} items")
            if "items" in s:
                for i, item in enumerate(v):
                    self._check(s["items"], item, f"{at}[{i}]", out)
        if isinstance(v, dict):
            for k in s.get("required", []):
                if k not in v:
                    out.append(f"{where}: missing {k!r}")
            props = s.get("properties", {})
            for k, item in v.items():
                sub = f"{at}.{k}" if at else str(k)
                if "propertyNames" in s:
                    self._check(s["propertyNames"], k, sub, out)
                if k in props:
                    self._check(props[k], item, sub, out)
                elif "additionalProperties" in s:
                    self._check(s["additionalProperties"], item, sub, out)
        if "anyOf" in s:
            if not any(not self._sub(alt, v) for alt in s["anyOf"]):
                out.append(f"{where}: matches none of the anyOf alternatives")

    def _sub(self, s, v):
        out = []
        self._check(s, v, "", out)
        return out


# --- semantic diff ---------------------------------------------------------------

_MISSING = object()


def _fmt(v):
    text = json.dumps(v, ensure_ascii=False)
    return text if len(text) <= 160 else text[:157] + "..."


def diff(a, b, path=()):
    """(leaf path, description) for every difference between two configurations.
    A side missing where the other holds a mapping or a list is read as an empty
    one, so a new subtree is reported leaf by leaf."""
    if a is _MISSING and isinstance(b, dict):
        a = {}
    if b is _MISSING and isinstance(a, dict):
        b = {}
    if a is _MISSING and isinstance(b, list):
        a = []
    if b is _MISSING and isinstance(a, list):
        b = []
    if isinstance(a, dict) and isinstance(b, dict):
        out = []
        for k in list(a) + [k for k in b if k not in a]:
            out += diff(a.get(k, _MISSING), b.get(k, _MISSING), path + (k,))
        return out
    if isinstance(a, list) and isinstance(b, list):
        if a == b:
            return []
        scalar = all(not isinstance(x, (dict, list)) for x in a + b)
        if not scalar:
            return [(path, f"changed from {_fmt(a)} to {_fmt(b)}")]
        added = [x for x in b if x not in a]
        removed = [x for x in a if x not in b]
        out = []
        if added:
            out.append((path, "added " + ", ".join(_fmt(x) for x in added)))
        if removed:
            out.append((path, "removed " + ", ".join(_fmt(x) for x in removed)))
        if not added and not removed:
            out.append((path, "same items, another order"))
        return out
    if a is _MISSING:
        return [(path, f"set to {_fmt(b)}")]
    if b is _MISSING:
        return [(path, f"removed (was {_fmt(a)})")]
    if type(a) is not type(b) or a != b:
        return [(path, f"changed from {_fmt(a)} to {_fmt(b)}")]
    return []


def dotted(path):
    return ".".join(str(p) for p in path) or "(root)"


def diff_markdown(changes):
    if not changes:
        return "- nothing: the configuration CodeRabbit reads is the same\n"
    return "".join(f"- `{dotted(p)}`: {d}\n" for p, d in changes)


# --- migration -------------------------------------------------------------------

def strip_managed(text, managed):
    """A hand-written file without what the managed part now carries: the
    exact lines the exclusion campaign wrote (each managed list item, its
    comment, and a key left with no item), and nothing else. The caller checks
    that this changes nothing once rendered, and keeps the file verbatim when
    it would."""
    items = set()
    for path in leaves(managed):
        v = managed
        for k in path:
            v = v[k]
        if isinstance(v, list):
            items.update(x for x in v if isinstance(x, str))
    forms = set()
    for x in items:
        forms |= {f'- "{x}"', f"- '{x}'", f"- {x}"}
    lines = text.split("\n")
    kept = [ln for ln in lines if ln.strip() not in forms and ln.strip() not in LEGACY_COMMENT]
    # A key whose list was only managed items is now `key:` with nothing under
    # it, which YAML reads as null: drop that line too.
    out = []
    for i, ln in enumerate(kept):
        m = re.match(r"^( *)([A-Za-z0-9_]+):\s*$", ln)
        if m:
            depth = len(m.group(1))
            nxt = next((n for n in kept[i + 1:] if n.strip() and not n.lstrip().startswith("#")), None)
            under = nxt is not None and (len(nxt) - len(nxt.lstrip(" ")) > depth
                                         or (nxt.lstrip(" ").startswith("- ")
                                             and len(nxt) - len(nxt.lstrip(" ")) == depth))
            if not under:
                continue
        out.append(ln)
    return "\n".join(out)


LOCAL_HEAD = (
    "# This repository's own part of its CodeRabbit configuration. CodeRabbit\n"
    f"# does not read this file: kodflow/post-commit enforce renders {YAML}\n"
    "# from it, with the fleet's central part laid on top. Edit this file, never\n"
    f"# {YAML}. {README}\n"
)


def migrate(central, hand_text):
    """The local file a hand-written configuration becomes: the same text, so
    its comments survive, without the managed items, with a header."""
    original = load_text(hand_text, "the hand-written file")
    want = overlay(original, central.managed)
    stripped = strip_managed(hand_text, central.managed)
    try:
        same = overlay(load_text(stripped, "the stripped file"), central.managed) == want
    except Refused:
        same = False
    body = stripped if same else hand_text
    lines = body.split("\n")
    if lines and lines[0].startswith("# yaml-language-server:"):
        return lines[0] + "\n" + LOCAL_HEAD + "\n".join(lines[1:])
    return LOCAL_HEAD + body


# --- plan ------------------------------------------------------------------------

def read(d, name):
    p = os.path.join(d, name)
    if not os.path.exists(p):
        return None
    with open(p, encoding="utf-8") as fh:
        return fh.read()


def plan(central, current):
    """(kind, {name: text to write}, [names to delete], body, note)."""
    local, deployed, legacy = read(current, LOCAL), read(current, YAML), read(current, YML)
    generated = deployed is not None and GENERATED in deployed.split("\n")[:3]
    # What CodeRabbit reads today, for the diff: .coderabbit.yaml when there is
    # one, else .coderabbit.yml.
    before_text = deployed if deployed is not None else legacy
    before_name = YAML if deployed is not None else (YML if legacy is not None else None)
    write, delete, notes = {}, [], []

    if local is not None:
        kind = "sync"
        new_local = None
        if deployed is not None and not generated:
            notes.append(f"{YAML} was edited by hand: it is replaced, its edits belong in {LOCAL}")
    elif deployed is not None and generated:
        kind = "sync"
        new_local = None
    elif before_text is not None:
        kind = "migrate"
        if deployed is not None and legacy is not None:
            raise Refused(f"both {YAML} and {YML} are hand-written: which one CodeRabbit reads is"
                          " not documented, so a person has to merge them into one")
        new_local = migrate(central, before_text)
        write[LOCAL] = new_local
    else:
        kind = "create"
        new_local = None

    text, after = central.render(new_local if new_local is not None else local)
    if deployed != text:
        write[YAML] = text
    if legacy is not None:
        delete.append(YML)

    before = load_text(before_text, before_name) if before_text is not None else None
    changes = diff(before, after) if before is not None else None
    if kind == "migrate":
        outside = [(p, d) for p, d in changes if p not in central.managed_leaves]
        if outside:
            raise Refused("the migration would change more than the managed keys: "
                          + "; ".join(f"{dotted(p)} {d}" for p, d in outside[:5]))
    if not write and not delete:
        kind = "present"
    if delete:
        notes.append(f"{YML} is removed: CodeRabbit would read it beside {YAML}")
    shown = changes if changes is not None else diff({}, after)
    return kind, write, delete, body(kind, before_name, shown, notes, central), "; ".join(notes)


def body(kind, before_name, changes, notes, central):
    managed = "".join(f"- `{dotted(p)}`\n" for p in sorted(central.managed_leaves))
    what = {
        "create": (
            f"This repository had no CodeRabbit file. This adds `{YAML}`, rendered by\n"
            "kodflow/post-commit from the fleet's central part and `defaults.yaml`\n"
            "(`inheritance: true`): the settings CodeRabbit applied here until now (the\n"
            "dashboard's) still apply, merged under the file, and the managed keys are\n"
            "added in front of them.\n"),
        "migrate": (
            f"This repository's CodeRabbit settings move, unchanged, to `{LOCAL}`,\n"
            "which belongs to this repository and which CodeRabbit does not read.\n"
            f"`{YAML}` becomes a rendering of that file with the fleet's central part\n"
            "laid on top, and kodflow/post-commit keeps it so. The comments of the\n"
            "original file stay in the local one; the exclusion lists it carried by hand\n"
            "are dropped there, since the central part now holds them.\n"),
        "sync": (
            f"`{YAML}` is a rendering of `{LOCAL}` (or of the fleet's defaults when there\n"
            "is none) with the fleet's central part on top, and it no longer matches. This\n"
            "renders it again.\n"),
        "present": "Nothing to change.\n",
    }[kind]
    parts = ["## CodeRabbit: central part + this repository's own\n\n", what, "\n",
             "### What changes in the configuration CodeRabbit reads\n\n"]
    if before_name is None:
        parts.append(f"There was no file before. The new `{YAML}` sets:\n\n")
        parts.append(diff_markdown(changes))
    else:
        parts.append(f"Compared, key by key, with the `{before_name}` on the default branch"
                     " (comments ignored):\n\n")
        parts.append(diff_markdown(changes))
    if notes:
        parts.append("\n" + "".join(f"> {n}\n" for n in notes))
    parts.append(
        "\n### The keys this repository cannot change\n\n" + managed +
        "\nA managed list always holds the central items first; the local file can\n"
        "add items after them. Everything else is this repository's own: edit\n"
        f"`{LOCAL}`, and the next enforce run renders `{YAML}` again.\n"
        f"Details: {README}\n")
    return "".join(parts)


# --- CLI -------------------------------------------------------------------------

def _args(argv, spec):
    out, rest = {}, []
    it = iter(argv)
    for a in it:
        if a in spec:
            try:
                out[a] = next(it)
            except StopIteration:
                raise SystemExit(f"usage: {a} takes a value") from None
        elif a.startswith("--"):
            raise SystemExit(f"usage: unknown option {a}")
        else:
            rest.append(a)
    return out, rest


def main(argv):
    if not argv:
        print(__doc__, file=sys.stderr)
        return 2
    cmd, argv = argv[0], argv[1:]
    try:
        if cmd == "plan":
            o, _ = _args(argv, {"--root", "--owner", "--current", "--out"})
            if set(o) != {"--root", "--owner", "--current", "--out"}:
                print("usage: plan --root DIR --owner OWNER --current DIR --out DIR", file=sys.stderr)
                return 2
            central = Central(o["--root"], o["--owner"])
            kind, write, delete, text, note = plan(central, o["--current"])
            out = o["--out"]
            os.makedirs(os.path.join(out, "write"), exist_ok=True)
            for name, content in write.items():
                with open(os.path.join(out, "write", name), "w", encoding="utf-8") as fh:
                    fh.write(content)
            for name, content in (("kind", kind + "\n"), ("delete", "".join(d + "\n" for d in delete)),
                                  ("body.md", text), ("note", note + "\n")):
                with open(os.path.join(out, name), "w", encoding="utf-8") as fh:
                    fh.write(content)
            return 0
        if cmd == "render":
            o, _ = _args(argv, {"--root", "--owner", "--local"})
            central = Central(o["--root"], o["--owner"])
            local = None
            if "--local" in o:
                with open(o["--local"], encoding="utf-8") as fh:
                    local = fh.read()
            sys.stdout.write(central.render(local)[0])
            return 0
        if cmd == "validate":
            o, files = _args(argv, {"--root"})
            v = Validator(os.path.join(o.get("--root", "."), "schema.v2.json"))
            bad = 0
            for f in files:
                problems = v.errors(load_file(f))
                for p in problems:
                    print(f"{f}: {p}")
                bad |= bool(problems)
            return 1 if bad else 0
        if cmd == "diff":
            _, files = _args(argv, set())
            if len(files) != 2:
                print("usage: diff BEFORE AFTER", file=sys.stderr)
                return 2
            sys.stdout.write(diff_markdown(diff(load_file(files[0]), load_file(files[1]))))
            return 0
    except Refused as e:
        print(f"refused: {e}", file=sys.stderr)
        return 3
    print(f"usage: unknown command {cmd}", file=sys.stderr)
    return 2


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
